import { defineConfig } from "vite";

// Служебный работник собирается ОТДЕЛЬНО и кладётся рядом с `index.html`.
//
// Отдельно — потому что его правила он делит с приложением (`lib/offline.ts`),
// а общий сборщик вынес бы общее в отдельный кусок и сделал бы `sw.js` модулем
// с импортом. Модульные служебные работники есть не везде, и промах был бы тихим:
// приложение работает, офлайна просто нет. Здесь всё нужное вкладывается внутрь
// одним файлом (`iife`).
//
// Рядом с `index.html`, а не в `assets/` — потому что область действия работника
// ограничена его собственной папкой: из `assets/` он управлял бы только ею.
// Имя без хэша — по нему браузер узнаёт работника и сверяет, не изменился ли он.
export default defineConfig({
  build: {
    outDir: "dist",
    emptyOutDir: false,            // основная сборка уже прошла, чистить нечего
    target: "es2020",
    lib: {
      entry: "src/sw.ts",
      formats: ["iife"],
      name: "parkreadServiceWorker",
      fileName: () => "sw.js",
    },
  },
});
